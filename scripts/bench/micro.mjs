// Times the heavy functions directly (no server), on generated data. Usage: node micro.mjs --repo <worktree> --data <seeded root from seed.mjs>
import path from 'node:path';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const arg = k => process.argv[process.argv.indexOf('--' + k) + 1];
const repo = path.resolve(arg('repo')), root = path.resolve(arg('data'));
fs.mkdirSync(path.join(root, 'userhome'), { recursive: true });
process.env.JADE_HOME = path.join(root, 'home'); process.env.JADE_CLAUDE_HOME = path.join(root, 'claude'); process.env.HOME = path.join(root, 'userhome'); process.env.JADE_TOKEN = 'x';
const imp = f => import(pathToFileURL(path.join(repo, 'server', 'core', f)).href);
const [config, store, files, memory, outputs, agents, skills, jobs, search] = await Promise.all(['config.js', 'store.js', 'files.js', 'memory.js', 'outputs.js', 'agents.js', 'skills.js', 'jobs.js', 'search.js'].map(imp));
config.load(); store.init();
const out = {};
const time = (name, f, n = 1) => { const ms = []; for (let i = 0; i < n; i++) { const t = performance.now(); f(); ms.push(performance.now() - t); } ms.sort((a, b) => a - b); out[name] = { n, medianMs: +ms[Math.floor(n / 2)].toFixed(2), worstMs: +ms.at(-1).toFixed(2) }; console.error(name, out[name]); };
time('store.listProjects (20)', () => store.listProjects(), 20);
time('store.listNotes (2,000)', () => store.listNotes(), 5);
time('store.listActions (3,000)', () => store.listActions(), 10);
time('store.listThreads (50x200 turns)', () => store.listThreads(), 10);
time('store.getThread (one of 50)', () => store.getThread('c-0'), 10);
time('store.appendTurn (rewrites chats.json)', () => store.appendTurn('c-5', { role: 'user', text: 'x' }), 5);
time('agents.list (re-reads every agent file)', () => agents.list(), 20);
time('agents.get (one agent, same cost)', () => agents.get('jade'), 20);
time('skills.list (re-reads every skill)', () => skills.list(), 20);
time('jobs.list', () => jobs.list(), 20);
time('files.isSecret (one path)', () => files.isSecret('/tmp/x/a/b/c.md'), 2000);
time('files.scan(force) 20,000 files', () => files.scan(true), 3);
time('files.search (cached list)', () => files.search('budget', { limit: 50 }), 10);
time('outputs.listOutputs (cached list)', () => outputs.listOutputs({ limit: 200 }), 5);
time('memory.rebuild (first, 8,000 files cap)', () => memory.rebuild(), 1);
time('memory.rebuild (again, nothing changed)', () => memory.rebuild(), 2);
time('memory.search', () => memory.search('budget review', 12), 20);
time('memory.listFiles', () => memory.listFiles([]), 5);
time('search.search (documents+files+chats)', () => search.search('budget review', { limit: 12 }), 5);
console.log(JSON.stringify(out, null, 2));
process.exit(0);
